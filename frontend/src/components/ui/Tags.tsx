import type { ReactNode } from "react";
import { riskTone } from "@/lib/format";

export type SourceKind = "curated" | "ai" | "gbif" | "community" | "contributor";

const sourceStyle: Record<SourceKind, { label: string; className: string; title: string }> = {
  curated: {
    label: "Curated DB",
    className: "bg-src-curated-tint text-src-curated",
    title: "From the reviewed AlgaeAI species database",
  },
  ai: {
    label: "AI estimate",
    className: "bg-src-ai-tint text-src-ai",
    title: "Generated by the AI model. Verify before relying on it.",
  },
  gbif: {
    label: "GBIF",
    className: "bg-src-gbif-tint text-src-gbif",
    title: "From the Global Biodiversity Information Facility",
  },
  community: {
    label: "Community",
    className: "bg-src-community-tint text-src-community",
    title: "Contributed by the community and approved by a reviewer",
  },
  contributor: {
    label: "Contributor",
    className: "bg-src-community-tint text-src-community",
    title: "Supplied by the contributor, not yet reviewed",
  },
};

/** Where a piece of data came from. Shown next to every data panel. */
export function SourceTag({ kind, label }: { kind: SourceKind; label?: string }) {
  const s = sourceStyle[kind];
  return (
    <span
      title={s.title}
      className={`inline-flex shrink-0 items-center rounded px-1.5 py-0.5 font-mono text-[10px] font-medium tracking-[0.08em] uppercase ${s.className}`}
    >
      {label ?? s.label}
    </span>
  );
}

const riskStyle = {
  high: "bg-risk-high-tint text-risk-high border-risk-high-line",
  medium: "bg-risk-medium-tint text-risk-medium border-risk-medium-line",
  low: "bg-brand-tint text-brand border-[#c4dccd]",
  none: "bg-brand-tint text-brand border-[#c4dccd]",
  unknown: "bg-paper text-muted border-line",
};

export function RiskBadge({ level, children }: { level?: string; children?: ReactNode }) {
  const tone = riskTone(level);
  return (
    <span className={`inline-flex items-center gap-1 rounded-md border px-2 py-0.5 text-xs font-medium ${riskStyle[tone]}`}>
      {children ?? (tone === "unknown" ? "Risk unknown" : tone === "none" ? "No known toxins" : `${level} risk`)}
    </span>
  );
}

const statusStyle: Record<string, string> = {
  pending: "bg-paper text-muted border-line",
  needs_revision: "bg-risk-medium-tint text-risk-medium border-risk-medium-line",
  approved: "bg-brand-tint text-brand border-[#c4dccd]",
  rejected: "bg-risk-high-tint text-risk-high border-risk-high-line",
};

export const statusLabel: Record<string, string> = {
  pending: "In review",
  needs_revision: "Needs revision",
  approved: "Approved",
  rejected: "Not accepted",
};

export function StatusBadge({ status }: { status: string }) {
  return (
    <span className={`inline-flex items-center rounded-md border px-2 py-0.5 text-xs font-medium ${statusStyle[status] ?? statusStyle.pending}`}>
      {statusLabel[status] ?? status}
    </span>
  );
}
